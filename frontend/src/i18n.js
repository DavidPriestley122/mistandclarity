// Get the current language, defaulting to 'en'
export function getLang() {
  return localStorage.getItem('lang') || 'en';
}

// Set the language and update <html lang>
export function setLanguage(lang) {
  localStorage.setItem('lang', lang);
  document.documentElement.lang = lang === 'zh' ? 'zh-Hant' : 'en';
}

// Dot-notation translation lookup, falls back to English
export function t(key) {
  const lang = getLang();
  const parts = key.split('.');
  let result = translations[lang];
  for (const part of parts) {
    if (result == null) break;
    result = result[part];
  }
  if (result != null) return result;

  // Fallback to English
  let fallback = translations.en;
  for (const part of parts) {
    if (fallback == null) break;
    fallback = fallback[part];
  }
  return fallback ?? key;
}

// Exhibition field helper: returns field_zh if in zh mode and non-empty, else field
export function tExhibition(collection, field) {
  if (!collection) return '';
  if (getLang() === 'zh') {
    const zhValue = collection[field + '_zh'];
    if (zhValue) return zhValue;
  }
  return collection[field] || '';
}

// Apply the stored language to <html lang> on load
(function init() {
  document.documentElement.lang = getLang() === 'zh' ? 'zh-Hant' : 'en';
})();
